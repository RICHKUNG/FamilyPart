#!/usr/bin/env python3
"""
Batch evaluation script for multiple scenes using integrated AggregationPipeline.

This script:
1. Uses AggregationPipeline to generate 3D proposals with SigLIP features
2. Saves aggregation results to {exp_dir}/aggregation_result/
3. Runs InferencePipeline with configurable parameters
4. Saves inference results to {exp_dir}/inference_result/
5. Evaluates using Search3D protocol
6. Aggregates results across scenes

Usage:
    # Evaluate single scene with default settings
    python scripts/batch_eval_experiment.py \
        --exp-root /path/to/experiment/root \
        --dataset-root /path/to/multiscan \
        --gt-path /path/to/annotations \
        --scenes scene_00005_00

    # Evaluate all scenes without SigLIP features (faster)
    python scripts/batch_eval_experiment.py \
        --exp-root /path/to/experiment/root \
        --dataset-root /path/to/multiscan \
        --gt-path /path/to/annotations \
        --no-extract-features

    # Evaluate with custom inference config
    python scripts/batch_eval_experiment.py \
        --exp-root /path/to/experiment/root \
        --dataset-root /path/to/multiscan \
        --gt-path /path/to/annotations \
        --inference-config configs/inference/hierarchical.yaml

Features:
- Uses integrated pipeline.ipynb workflow via AggregationPipeline
- Generates 3D point cloud masks (79,614 points) compatible with Search3D
- Default: Extracts SigLIP features for accurate retrieval
- Saves structured results in experiment directories
- Supports batch processing of multiple scenes
- Configurable inference strategy and parameters
"""

